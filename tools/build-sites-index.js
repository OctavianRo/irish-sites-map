#!/usr/bin/env node
/**
 * Extracts the site list embedded in index.html into a slim, standalone
 * destination index for the haulage planner (assets/sites-index.js).
 *
 * The planner only needs enough to find and label a delivery point, so the
 * long planning-file descriptions and URLs are dropped. Emitting a plain
 * script that assigns a global (rather than JSON) keeps fleet.html working
 * from file:// as well as from a web server.
 *
 *   node tools/build-sites-index.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'index.html');
const OUT = path.join(ROOT, 'assets', 'sites-index.js');

const LAT = 0, LON = 1, CAT = 2, UNITS = 3, AUTH = 4, APP = 5, GRANT = 6, ADDR = 9;

function extract(html) {
  const line = html.split('\n').find(l => l.startsWith('const DATA='));
  if (!line) throw new Error('could not find "const DATA=" in index.html');
  return JSON.parse(line.replace(/^const DATA=/, '').replace(/;\s*$/, ''));
}

const data = extract(fs.readFileSync(SRC, 'utf8'));

// Authorities are highly repetitive - intern them into a lookup table.
const authorities = [...new Set(data.sites.map(s => s[AUTH] || ''))].sort();
const authIndex = new Map(authorities.map((a, i) => [a, i]));

const round = (n, dp) => Number(Number(n).toFixed(dp));

const sites = data.sites.map(s => ([
  round(s[LAT], 5),
  round(s[LON], 5),
  s[CAT] | 0,
  s[UNITS] | 0,
  authIndex.get(s[AUTH] || ''),
  s[APP] || '',
  (s[GRANT] || '').slice(0, 7),   // YYYY-MM is enough for the planner
  (s[ADDR] || '').replace(/\s+/g, ' ').trim().slice(0, 120),
]));

const payload = {
  generated: new Date().toISOString().slice(0, 10),
  categories: data.categories,
  authorities,
  fields: ['lat', 'lon', 'cat', 'units', 'auth', 'ref', 'granted', 'addr'],
  sites,
};

const body = `/* Generated by tools/build-sites-index.js - do not edit by hand. */
window.SITE_INDEX = ${JSON.stringify(payload)};
`;

fs.writeFileSync(OUT, body);
console.log(`wrote ${path.relative(ROOT, OUT)}: ${sites.length} sites, ${(body.length / 1024).toFixed(0)} KB`);
